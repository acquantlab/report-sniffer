def _pdf(path: Path, pages: list[list[tuple]]) -> bytes:
    """pages of (x, y, text, right-aligned) lines."""
    from reportlab.lib.pagesizes import letter
    from reportlab.pdfgen import canvas
    c = canvas.Canvas(str(path), pagesize=letter)
    for lines in pages:
        for x, y, s, right in lines:
            c.setFont("Helvetica", 9)
            (c.drawRightString if right else c.drawString)(x, y, s)
        c.showPage()
    c.save()
    return path.read_bytes()


def _page(head: list[str], cols: list[str], rows: list[tuple], top: int = 740) -> list[tuple]:
    """head lines, then the column header, then rows (label, *amounts); a row without amounts is a heading, a row
    with an empty label is an unlabeled total; a label "a|b" is wrapped onto two lines."""
    xs = [400, 470, 540][-len(cols):]
    out, y = [], top
    for h in head:
        out.append((50, y, h, False))
        y -= 14
    out += [(x, y, c, True) for x, c in zip(xs, cols)]
    y -= 18
    for label, *vals in rows:
        if "|" in label:
            first, label = label.split("|")
            out.append((50, y, first, False))
            y -= 12
        if label:
            out.append((50, y, label, False))
        out += [(x, y, v, True) for x, v in zip(xs[-len(vals):] if vals else [], vals)]
        y -= 14
    return out


def _run(tmp_path, pages):
    data = _pdf(tmp_path / "doc.pdf", [[(50, 740, "Example Holdings, Inc.", False)]] + pages)
    return pipeline.run({"kind": "upload", "data": data, "name": "doc.pdf", "lang": "en"}, lambda *_: None)


