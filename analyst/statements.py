def _titles(text: str, limit: int = 700):
    """Statement titles in the opening of a page that are headings, not mentions in a sentence: the title starts
    with a capital ("Consolidated Balance Sheets", "CONSOLIDATED STATEMENTS OF INCOME", "Consolidated statements of
    income"), the word before it is not a lowercase one ("in the Consolidated Balance Sheets", "the summarized balance
    sheet information") and it does not end a sentence ("Consolidated Balance Sheets. During the year…")."""
    for m in _title_spots(text, limit):
        q = _QUAL.search(text[max(0, m.start() - 60):m.start()])
        start = m.start() - (len(q.group()) if q else 0)
        if not text[start:start + 1].isupper() and not (start < 200 and re.match(r"\s*[\(A-Z\d]", text[m.end():m.end() + 20])):
            continue                                   # lowercase, unless a heading set in lowercase ("intel corporation
                                                       # consolidated statements of income  Years Ended (In Millions…")
        prev = re.search(r"([A-Za-z][\w'’&.-]*)[^\w]*$", text[max(0, start - 40):start])
        if prev and (re.fullmatch(PROSE_WORD, prev.group(1)) or re.search(r"['’]s$", prev.group(1))):
            continue                                   # "in the …", "the Company's Consolidated Statements of …"
        if re.match(r"\.(\s|$)", text[m.end():m.end() + 30]):
            continue                                   # a title ends no sentence: "… in the Consolidated balance sheets."
        nxt = re.match(r"[ \t]*([a-z]\w*)", text[m.end():m.end() + 30])
        if nxt and nxt.group(1) not in ("for", "years", "year", "as", "at", "and", "of", "in"):
            continue                                   # "… Statements of Cash Flows illustrating the effect of …"
        if re.match(r"\W*(the following|this (table|section)|below|we |our |(and [\w ]{1,30})?(analysis|data|discussion|highlights|summary|review)\b)",
                    text[m.end():m.end() + 60], re.I):
            continue                                   # a section of the MD&A about the statement ("… balance sheets analysis")
        yield m


def _title_spots(text: str, limit: int):
    yield from STATEMENT_TITLE.finditer(text[:limit])
    top = _head(text, 150)
    prose = re.search(r"\.\s+\w|\b([a-z]+\s+){6}", top)          # a sentence, not a column header ("… we have recast certain prior …")
    if limit < len(text) and len(header_years(top)) >= 2 and not prose \
            and (HEADER_NEAR.search(top) or re.search(r"\d,\d{3}", _head(text, 300))):
        # some PDFs give the page's title last ("…Weighted-average diluted shares 2,970.0 … Consolidated statements of
        # income  JPMorgan Chase & Co./2022 Form 10-K 159"): a title in the closing lines of a page that opens with columns
        yield from STATEMENT_TITLE.finditer(text, max(limit, len(text) - 250))


def title_match(text: str, limit: int = 700):
    return next(_titles(text, limit), None)


