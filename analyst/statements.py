DATE_RE = re.compile(r"\b(jan|feb|mar|apr|may|jun|jul|aug|sep|sept|oct|nov|dec)[a-z]*\.?\s+(\d{1,2}),?\s+((?:19|20)\d\d)\b", re.I)
QUARTER_RE = re.compile(r"\b(?:([1-4])Q\s?['’]?(\d{2}|\d{4})|Q([1-4])\s?['’]?(\d{2}|\d{4}))\b")


def header_quarters(text: str) -> list[tuple[int, int]]:
    """Quarter codes heading the columns ("1Q23 4Q22 … 1Q22", "Q2 2023 Q2 2022") as (year, quarter)."""
    out, last = [], None
    for m in QUARTER_RE.finditer(text[:2500]):
        q = int(m.group(1) or m.group(3))
        y = int(m.group(2) or m.group(4))
        y = y + 2000 if y < 100 else y
        if last is not None and m.start() - last > 45:
            if len(out) >= 2:
                break
            out = []
        out.append((y, q))
        last = m.start()
    return out if len(out) >= 2 and len(set(out)) > 1 else []


def header_dates(text: str, years: list[int]) -> list:
    """The full date of each column when the header prints it ("June 2, 2023  December 2, 2022")."""
    from datetime import date
    import calendar
    dots = dot_dates(text)
    if dots and [d.year for d in dots] == years:
        return dots
    out = []
    for m in DATE_RE.finditer(text[:2500]):
        mo = MONTH_NO[m.group(1).lower()[:3]]
        y = int(m.group(3))
        out.append(date(y, mo, min(int(m.group(2)), calendar.monthrange(y, mo)[1])))
        if len(out) >= len(years):
            break
    if len(out) >= 2 and [d.year for d in out[:len(years)]] == years[:len(out)]:
        return out
    # "January 28,  January 29," on one line and "2023  2022" on the next: pair them in order
    # where the run of column years starts (a year in the page heading comes earlier and is not it)
    hits = [(x.start(), int(x.group(1))) for x in YEAR.finditer(text[:2500])]
    first_year = None
    for i in range(len(hits) - len(years) + 1):
        seq = hits[i:i + len(years)]
        if [y for _, y in seq] == years and all(b[0] - a[0] <= 45 for a, b in zip(seq, seq[1:])):
            first_year = seq[0][0]
            break
    if first_year is None:
        return []
    mds = re.findall(r"\b(jan|feb|mar|apr|may|jun|jul|aug|sep|sept|oct|nov|dec)[a-z]*\.?\s+(\d{1,2}),?(?!\s*,?\s*(?:19|20)\d\d)",
                     text[max(0, first_year - 200):first_year], re.I)
    if len(mds) < len(years):
        return []
    mds = mds[-len(years):]
    try:
        return [date(y, MONTH_NO[mo.lower()[:3]], min(int(d), calendar.monthrange(y, MONTH_NO[mo.lower()[:3]])[1])) for (mo, d), y in zip(mds, years)]
    except ValueError:
        return []


# a date written with dots, as European reports head their columns ("31.12.2023", "31.12.23"); with slashes the year
# is seen by YEAR already
DOT_DATE = re.compile(r"(?<![\d.,])(\d{1,2})\.(\d{1,2})\.((?:19|20)?\d\d)(?![\d,]|\.\d)")


def dot_dates(text: str) -> list:
    """The dates of a line of the header written with dots, when it has two or more years: "31.12.23 31.12.22 30.09.23"."""
    from datetime import date
    for line in text[:2500].splitlines():
        out = []
        for m in DOT_DATE.finditer(line):
            d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
            try:
                out.append(date(y + 2000 if y < 100 else y, mo, d))
            except ValueError:
                pass
        if out and out[0] in out[1:]:
            out = out[:out.index(out[0], 1)]       # two tables side by side, each with its dates: the first one's
        if len(out) >= 2 and len({x.year for x in out}) > 1:
            return out
    return []


def header_years(text: str) -> list[int]:
    """The years heading the columns, in their order: the first run of two or more different years printed close
    together ("2017 2018 2019", "June 30, 2023 July 1, 2022", "2023 2022 2023 2022"; "31.12.23 31.12.22")."""
    dots = dot_dates(text)
    if dots:
        return [d.year for d in dots]
    # a line made of years is the column header, even under a dateline that names them too
    # ("Fiscal years ended December 31, 2022, December 25, 2021 and …" / "2022 2021 2020")
    for line in text[:2500].splitlines():
        toks = line.replace("$", " ").split()
        ys = [int(x) for x in toks if YEAR.fullmatch(x)]
        if len(ys) >= 2 and len(set(ys)) > 1 and all(YEAR.fullmatch(x) or x.lower() in ("note", "notes", "nota", "note:", "%", "change") for x in toks):
            return ys
    run: list[tuple[int, int]] = []
    for m in YEAR.finditer(text[:2500]):
        pos, y = m.start(), int(m.group(1))
        if run and pos - run[-1][0] <= 45 and abs(y - run[-1][1]) <= 3:
            run.append((pos, y))
            continue
        if len(run) >= 2 and len({v for _, v in run}) > 1:
            break
        run = [(pos, y)]
    ys = [y for _, y in run] if len(run) >= 2 and len({v for _, v in run}) > 1 else []
    if ys:
        # a dateline just above the header names the years in prose ("Years Ended May 31, 2023, 2022 and 2021"
        # reads as 2022 2021): the header right after it, with a later year, is the one
        later = header_years(text[run[-1][0] + 4:run[0][0] + 400]) if run[-1][0] + 4 < len(text) else []
        if later and max(later) > max(ys):
            return later
    # a dateline running into the header ("… 2022, 2021, and 2020  2022 2021 2020" read as 2020 2022 2021 2020):
    # columns are in order (2022 2021 2020), or the same block twice (2023 2022 2023 2022)
    def ordered(v):
        mono = lambda s: len(s) >= 2 and (all(a > b for a, b in zip(s, s[1:])) or all(a < b for a, b in zip(s, s[1:])))
        return mono(v) or (len(v) % 2 == 0 and v[:len(v) // 2] == v[len(v) // 2:] and mono(v[:len(v) // 2]))
    while len(ys) > 3 and not ordered(ys) and ordered(ys[1:]):
        ys = ys[1:]
    return ys


def page_period(text: str) -> dict:
    """What the columns of a statement page are: their length in months (None for a balance sheet date) and end."""
    lo = text[:2500].lower()
    months = None
    for pat, m in ((r"three months|(twelve|thirteen|sixteen|12|13|16) weeks|quarters? ended|(first|second|third|fourth)[- ]quarter|tre mesi|trimestre", 3),
                   (r"six months|(twenty-four|twenty-six|24|26) weeks|half[- ]year|sei mesi|semestre", 6),
                   (r"nine months|(thirty-six|thirty-nine|thirty-six|36|39|40) weeks|nove mesi", 9),
                   (r"years? ended|fiscal years? ended|twelve months|(fifty-two|fifty-three|52|53) weeks|esercizio", 12)):
        pos = re.search(pat, lo)
        if pos and (months is None or pos.start() < months[1]):
            months = (m, pos.start())
    md = re.search(r"(?:ended|ending|as of|as at|at)\s+(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+(\d{1,2})\b", lo)
    fq = re.search(r"\b(first|second|third|fourth)[- ]quarter\b", lo)
    instant = months is None and bool(re.search(r"balance sheet|financial position|as of|as at|stato patrimoniale|situazione patrimoniale", lo))
    if md is None and instant:
        # a balance sheet headed by its date alone: "BALANCE SHEETS (In millions) June 30, 2023 2022"
        md = re.search(r"\b(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+(\d{1,2})\b", lo[:400])
    return {"months": months[0] if months else None, "month": MONTH_NO[md.group(1)] if md else 12,
            "day": int(md.group(2)) if md else 31, "instant": instant,
            "fiscal_q": ["first", "second", "third", "fourth"].index(fq.group(1)) + 1 if fq and not md else None}


# which statement each item belongs to: its figure is taken from that statement when the document has it
IS_KEYS = {"revenue", "cost_of_revenue", "gross_profit", "rnd", "opex_total", "operating_income", "pretax_income", "income_tax",
           "net_income", "profit_total", "eps_diluted", "diluted_shares", "interest_expense"}
CF_KEYS = {"cfo", "cfi", "cff", "capex", "buybacks", "dividends", "sbc", "cash_change", "fx_effect", "cash_hfs"}
IS_TITLE = re.compile(r"statements? of (consolidated )?((\((loss|income)\) )?(operations|income|earnings)|comprehensive (\(loss\) )?(income|loss))"
                      r"|income statements?|statements? of profit (or|and) loss|profit and loss (account|statement)s?|conto economico", re.I)
CF_TITLE = re.compile(r"statements? of (consolidated )?cash flows?|cash flows? statements?|rendiconto finanziario", re.I)
BS_TITLE = re.compile(r"balance sheets?|statements? of (consolidated )?financial (position|condition)|stato patrimoniale|situazione patrimoniale", re.I)


def _line_rank(key: str, label: str) -> int:
    """Between two lines of the same statement: total revenue before net sales, the result attributable to
    the company before the result including minority interests."""
    if key == "revenue":
        return 2 if label.startswith("total") else 1
    if key == "net_income":
        return 2 if "attributable to" in label else 1
    if key in ("cfo", "cfi", "cff"):
        # the total before its continuing-operations part; IFRS "cash generated from operations" is before interest and taxes
        return (2 if "activities" in label and not label.startswith("cash generated") else 1) * 2 - ("continuing operations" in label)
    if key == "eps_diluted":
        # a row named as diluted EPS before one read under a heading; the net result before continuing operations
        return (2 if not label.endswith("(heading)") else 0) + ("continuing operations" not in label)
    if key == "equity":
        # the total with minority interests ("Total equity", "Total stockholders' equity" next to "Total Intel
        # stockholders' equity"), as the tagged filings' first concept
        return 2 if re.fullmatch(r"total (equity|(stockholders|shareholders|shareowners|share-holders)['’]? (equity|deficit|investment))( \(deficit\))?",
                                 label) else 1
    if key == "buybacks":
        return 1 if "treasury" in label else 2       # shares bought back, not treasury shares bought for employee plans
    return 0


def tax_expense(label: str, value: float) -> float:
    """The tax line as an expense (a benefit is negative), from the direction its label states: "Provision for
    (benefit from) income taxes" prints the expense as it is, "Income tax (expense) benefit" and "(Provision for)
    benefit from income taxes" print it in parentheses. A label naming one direction only: its amount, unsigned."""
    s = _clean(label)
    if re.search(r"\((provision|expense)( for| from)?\)", s):
        return -value
    if re.search(r"\(benefit( for| from)?\)", s):
        return value
    if "benefit" in s and not re.search(r"provision|expense", s):
        return -abs(value)
    return abs(value)


def statement_of(key: str) -> str:
    return "is" if key in IS_KEYS else "cf" if key in CF_KEYS else "bs"


def page_statement(text: str) -> str:
    titles = " | ".join(m.group() for m in _titles(text))
    for kind, rx in (("cf", CF_TITLE), ("bs", BS_TITLE), ("is", IS_TITLE)):
        if rx.search(titles):
            return kind
    return ""


def page_kinds(text: str) -> set:
    """Every statement printed on a page: a release's balance sheet under its cash flow statement, a balance sheet
    ending at the top of the page that then opens the statement of income."""
    out = set()
    for m in _headings(text):
        for kind, rx in (("cf", CF_TITLE), ("bs", BS_TITLE), ("is", IS_TITLE)):
            if rx.search(m.group()):
                out.add(kind)
                break
    return out


EQ_TITLE = re.compile(r"statements? of (consolidated )?(changes in )?(\w+ )?(stockholders|shareholders|shareowners|share-holders)['’]? (equity|investment)"
                      r"|(stockholders|shareholders|shareowners)['’]? equity statements?"
                      r"|statements? of (changes in )?equity|prospetto delle variazioni del patrimonio netto", re.I)


HEADER_NEAR = re.compile(r"(quarters?|years?|months|weeks|periods?) ended|\(in (millions|thousands|billions)|\((millions|thousands|dollars)|esercizio|migliaia|milioni", re.I)


def statement_start(text: str) -> int:
    """Where a statement printed lower on the page begins (a release's text above its statement of earnings):
    its title followed by its column header. 0 when the page opens with it, or holds none."""
    if title_match(text):
        return 0
    for m in _headings(text):
        return m.start()
    return 0


def foot_title(text: str):
    """A statement's title printed at the foot of a page that holds another statement, the statement itself overleaf
    ("… $ 154 $ 137  eBay Inc. Unaudited Condensed Consolidated Statement of Cash Flows  8")."""
    ms = list(_titles(text, len(text)))
    if len(ms) >= 2 and ms[-1].start() > len(text) - 150 and re.fullmatch(r"[\s\d|]*", text[ms[-1].end():]):
        return ms[-1]
    return None


def _headings(text: str):
    """The statement titles on a page that head a statement: at its top, or with a column header under them."""
    for m in _titles(text, len(text)):
        after = text[m.end():m.end() + 250]
        if m.start() < 700 or HEADER_NEAR.search(after) or len(header_years(after)) >= 2:
            yield m


# statements that are not the group's own: the parent company alone, guarantor / consolidating columns
# the amounts on a page: three or more digits ("1,234", "(567)"), or one decimal ("79.7", "-618.5", "€ million" reports),
# not a percentage
FIGURES = re.compile(r"\(?\d[\d,]{2,}\)?|(?<![\w.,])\(?-?\d{1,3}[.,]\d\)?(?![\d%])")


NOT_PRIMARY = (r"parent company|condensed financial information of (the )?registrant|\bregistrant\b|schedule i\b|capogruppo|separate financial statements"
               r"|bilancio separato|statutory financial statements|consolidating|guarantor|non-guarantor|\bissuer\b"
               r"|summari[sz]ed (statements? of|financial|balance sheet|income statement)|summary of [\w ]{0,30}financial information"
               r"|results? of the segments?\b|\bby (operating |business )?segments?\b"
               r"|\bfor the (\d(st|nd|rd|th)|first|second|third|fourth) quarter of (19|20)\d\d\b|on a proportionate basis|\beliminations\b"
               # a statement of the legal entity, not the group: "Income statement - Elkem ASA"
               r"|(statement|sheet)s?\b[^\n]{0,30}\s[-–—]\s+(?-i:[A-Z])[\w&.' -]{1,40}?\s(?-i:ASA|AB|AG|SE|S\.A\.|SA|N\.V\.|NV|Oyj|plc|A/S|S\.p\.A\.)\b"
               r"(?!\s+(and (its )?subsidiaries|group|consolidated))")


BOILERPLATE = re.compile(r"(the |see )?(accompanying )?notes to (the )?(consolidated )?financial statements are an integral part of (these|this)"
                         r"( consolidated)?( financial)? statements?\.?|see (the )?accompanying notes[^.]*\.?"
                         r"|see notes to (the )?(consolidated )?financial statements\.?", re.I)


def _head(text: str, n: int = 300) -> str:
    """The opening of a page without the statements' footer some PDFs give first ("The accompanying Notes … are an
    integral part of this statement. 49")."""
    return BOILERPLATE.sub(" ", text[:n + 200])[:n]


def _continues(text: str) -> bool:
    """A page that carries on the statement of the page before: no title of its own, not notes, statement rows."""
    if title_match(text) or re.search(r"notes to|report of independent|discussion and analysis", _head(text), re.I) \
            or EQ_TITLE.search(text[:300] + " " + text[-300:]):
        return False
    rows = 0
    for line in text.splitlines():
        label = re.split(r"\s[(\$—–-]*\d", line, maxsplit=1)[0]
        if label != line and match(label):
            rows += 1
    return rows >= 2 and len(FIGURES.findall(text)) >= 12


def statement_pages(texts: list[str]) -> list[int]:
    """0-based pages of the primary statements (income, balance sheet, cash flows): a page titled as one near its
    top and full of figures; consolidated before parent-company, the statement itself before its analysis or notes.
    For each statement: the first such page and the fullest one (they differ when a summary or a guarantor's
    statements share the title)."""
    best: dict[str, tuple] = {}
    first: dict[str, tuple] = {}
    for i, t in enumerate(texts):
        start = statement_start(t)
        t = t[start:]
        head = _head(t)                                 # not the footer some PDFs give first ("… Notes to …")
        kind = page_statement(t)
        if not kind or re.search(r"analysis of|notes to|discussion and analysis|report of independent|exhibits and financial statement schedules", head, re.I):
            continue
        title = title_match(t)
        if not title or not (HEADER_NEAR.search(t[title.end():title.end() + 300]) or header_years(t[title.end():title.end() + 300])
                             or title.start() > len(t) - 250):
            continue                                   # a title with its column header under it, not a mention
        figs = len(FIGURES.findall(t))
        if figs < 12:
            continue
        # the statement itself opens its page (or closes it, in PDFs that give the title last): a table titled so in a
        # note or the MD&A has text above it
        top = (start == 0 and title.start() < 200) or title.start() > len(t) - 250
        cond = bool(re.search(r"condensed", t[max(0, title.start() - 60):title.end() + 30], re.I))
        rank = (not re.search(NOT_PRIMARY, head, re.I), top, "consolidat" in (head + " " + title.group()).lower(),
                not re.search(r"comprehensive", head, re.I), not cond, figs)
        # alike, the earlier one: a report prints the group's statements before the parent company's (VERBUND: 54 and 63
        # figures), unless the later one is much fuller (the statement after a table of contents naming it: 20 and 39)
        if kind not in best or rank[:5] > best[kind][0][:5] or (rank[:5] == best[kind][0][:5] and 0.7 * figs > best[kind][0][5]):
            best[kind] = (rank, i)
        if kind not in first or rank[:5] > first[kind][0]:
            first[kind] = (rank[:5], i)
    foot = set()
    for i, t in enumerate(texts[:-1]):
        # a title at the foot of a page with the statement itself on the next one ("Consolidated Statements of Cash
        # Flows  $ in millions" / the columns overleaf)
        title = title_match(t)
        kind = page_statement(t)
        if kind and title and title.start() > len(t) - 300 and len(FIGURES.findall(t)) < 12 and _continues(texts[i + 1]):
            rank = (not re.search(NOT_PRIMARY, t[:300], re.I), True, "consolidat" in t[max(0, title.start() - 60):title.end()].lower(),
                    not re.search(r"comprehensive", title.group(), re.I),
                    not re.search(r"condensed", t[max(0, title.start() - 60):title.end() + 30], re.I), len(FIGURES.findall(texts[i + 1])))
            if kind not in best or rank > best[kind][0]:
                best[kind] = (rank, i + 1)
                foot.add(i)
            if kind not in first or rank[:5] > first[kind][0]:
                first[kind] = (rank[:5], i + 1)
                foot.add(i)
    pages = {i for _, i in best.values()} | {i for _, i in first.values()}
    pages |= {i for i in foot if i + 1 in pages}
    # the statement's next page, titled again ("… (continued)", or the title the PDF gives last)
    pages |= {i + 1 for i in pages if i + 1 < len(texts) and page_statement(texts[i + 1]) == page_statement(texts[i])
              and (re.search(r"continued", texts[i + 1][:300], re.I) or not re.search(r"comprehensive", (title_match(texts[i + 1]) or [""])[0], re.I))
              and len(FIGURES.findall(texts[i + 1])) >= 12}
    # a statement that goes on over the next page (its totals there), past a blank page
    nxt = {}
    for i in pages:
        j = i + 1
        if j < len(texts) and len(texts[j].strip()) < 20:
            j += 1
        if j < len(texts) and j not in pages and _continues(texts[j]):
            nxt[i] = j
    return sorted(pages | set(nxt.values()))


def _is_note_ref(f: dict, note_col: bool = False) -> bool:
    """A note number ("4") or a footnote mark the PDF prints apart from the label ("(2)"); under a "Note" column
    header, a note in parentheses too ("(16)", European reports) — elsewhere that is an amount (Pfizer's tax "(71)")."""
    return bool(re.fullmatch(r"\d{1,2}|\(\d\)" + (r"|\(\d{1,2}\)|\d{1,2}\.\d{1,2}|\d{1,2}(,\s?\d{1,2})+" if note_col else ""), f["display"].strip()))


NOTE_HEAD = re.compile(r"\bnotes?\s+(?:(?:group|company|consolidated|parent)\s+){0,3}(?:as (?:at|of)\s+)?(?:\d{1,2}[./]\d{1,2}[./]\d{2,4}|\d{1,2}\s+[a-z]+\.?\s+(?:19|20)\d\d|(?:19|20)\d\d\b"
                       r"|[$€£]|(?:eur|usd|dkk|sek|nok|chf|gbp|pln)\b)", re.I)


def note_column(text: str) -> bool:
    """A page whose column header, above its first amount, names a "Note" column ("EUR million Note 2023 2022",
    "Note 31.12.2023"); not "The accompanying Notes to the Consolidated Financial Statements" (Nike)."""
    first = re.search(r"(?<![\d.,])\d{1,3}[,.]\d{3}(?!\d)|(?<![\d.,])\d{1,3} \d{3}(?!\d)", text)   # the first amount, not "2023 2022", "31.12.2023"
    return bool(NOTE_HEAD.search(text[:max(min(first.start() if first else 800, 800), 3000 if NOTE_HEAD.search(text[:3000]) else 0)]))


def _drop_note_ref(nums: list, years: list, note_col: bool = False) -> list:
    """A "Note" column before the amounts ("Net sales  4  12,450  11,200"): a small whole number in front of
    more figures than the page has year columns. A two-digit amount in its own column stays."""
    if len(nums) >= 2 and _is_note_ref(nums[0], note_col):
        cols = len(years) if len(years) >= 2 else 2
        if len(nums) > cols and len(nums) % cols:      # not a row printed twice ("$ 46 $ 303 $ 1,203" and again)
            return nums[1:]
    return nums


PS_FIGURE = re.compile(r"\(?-?\d{1,3}\.\d{2,3}\)?")


def is_per_share(f: dict) -> bool:
    """A figure printed like an amount per share: "1.94", "(0.82)", "($1.12)", "$ 3.58"."""
    return bool(PS_FIGURE.fullmatch(re.sub(r"[$€£\s]", "", f["display"])))


def _amounts(nums: list, key: str) -> list:
    """Drop "% of sales" and "% change" columns printed between the amounts (one decimal, at most 100), and keep
    amounts and per-share figures apart when one label heads both ("Net income attributable to …" over the
    amount and, again, over earnings per share; "Diluted" over EPS and over the share count)."""
    per_share = [f for f in nums if is_per_share(f)]
    if per_share and len(per_share) < len(nums):
        nums = per_share if key in PER_SHARE else [f for f in nums if f not in per_share]
    if key in PER_SHARE:
        return nums
    marked = [f for f in nums if f["display"].strip().endswith("%")]
    if marked and len(marked) < len(nums):
        nums = [f for f in nums if f not in marked]       # "Gross profit 511.4 45% 555.9 45%"
    if len(nums) < 3:
        return nums
    pct = [f for f in nums if re.fullmatch(r"\(?-?\d{1,3}\.\d\)?%?", f["display"].strip("$ ")) and abs(f["value"]) <= 100]
    if pct and len(pct) < len(nums) and all(re.search(r"\d[, ]\d{3}|^\(?\$?\s?\d+\)?$", f["display"].strip()) for f in nums if f not in pct):
        return [f for f in nums if f not in pct]
    return nums


CELL = re.compile(r"\(?-?\d[\d,]*(?:\.\d+)?\)?%?|[—–]|(?<![\w-])-(?![\w-])|[A-Za-z]")


def _with_dashes(nums: list, label: str, text: str, n: int) -> list:
    """A row with fewer amounts than columns, as one cell per column: an empty cell is printed as a dash
    ("Repurchases of common stock — (600,022) —") and becomes None, so the amounts keep their own columns."""
    want = [f["display"].strip("$€£ ") for f in nums]
    flat = re.sub(r"\s+", " ", text)
    for m in re.finditer(re.escape(re.sub(r"\s+", " ", label.strip())), flat, re.I):
        cells = []
        for t in CELL.finditer(flat, m.end(), min(len(flat), m.end() + 240)):
            if t.group().isalpha():
                break
            cells.append(None if t.group() in "—–-" else t.group())
        amounts = [c for c in cells if c is not None]
        if len(cells) == n and len(amounts) < n and amounts == want:
            it = iter(nums)
            return [None if c is None else next(it) for c in cells]
        if len(cells) == n and want and [c for c in amounts if c in want] == want:
            # an amount not read as a figure (a lone digit: "— (6) 8") keeps its column, unread
            it, out = iter(nums), []
            pending = list(want)
            for c in cells:
                if c is not None and pending and c == pending[0]:
                    pending.pop(0)
                    out.append(next(it))
                else:
                    out.append(None)
            return out
    return nums


def _right(f: dict) -> float:
    """Where an amount ends on the page, its closing parenthesis aside (columns align on the digits)."""
    return f["x1"] - (3.5 if f["display"].rstrip().endswith(")") else 0)


def page_columns(facts: list[dict], note_col: bool = False) -> list[float]:
    """The columns of amounts on a PDF page: where the formatted amounts end, grouped (left to right). A column of
    percentages ("Percent to Sales", "% Change": one decimal, no thousands) is not one of them."""
    fs = sorted((f for f in facts if "x1" in f and re.search(r"\d[, ]\d{3}|\(\d|\d[.,]\d", f["display"])), key=_right)
    groups: list[list[dict]] = []
    for f in fs:
        if groups and _right(f) - _right(groups[-1][-1]) <= 8:
            groups[-1].append(f)
        else:
            groups.append([f])

    def percent(g):
        one = sum(1 for f in g if re.fullmatch(r"\(?-?\d{1,3}\.\d\)?%?", f["display"].strip("$ ")))
        return one >= 0.8 * len(g)

    def notes(g):                                  # a "Note" column: "(12)", "(16)"; "2.3" under a "Note" header (European reports)
        return all(re.fullmatch(r"\(\d{1,2}\)", f["display"].strip()) for f in g) \
            or (note_col and g is first and all(re.fullmatch(r"\(?\d{1,2}(\.\d{1,2})?\)?", f["display"].strip()) for f in g))
    first = next((g for g in groups if len(g) >= 3), None)
    return [_right(sorted(g, key=_right)[len(g) // 2]) for g in groups if len(g) >= 3 and not percent(g) and not notes(g)]


def by_position(nums: list, cols: list[float], n: int) -> Optional[list]:
    """A row's amounts put under the columns they sit in: an empty cell stays empty, a note number or a footnote mark
    outside the columns is left out, a row printed twice under the same label keeps its first figures. None when the
    page's columns are not the header's (percentages, notes) or a figure has no position."""
    if n < 2 or len(cols) != n or not nums or any("x1" not in f for f in nums):
        return None
    cells: list = [None] * n
    placed = False
    for f in nums:
        i = min(range(n), key=lambda k: abs(cols[k] - _right(f)))
        if abs(cols[i] - _right(f)) > 12:
            continue
        if cells[i] is None:
            cells[i] = f
            placed = True
    return cells if placed else None


def _columns(nums: list, years: list, quarters: Optional[list] = None, dates: Optional[list] = None) -> tuple:
    """(current, comparative) figure of a row, by the years (or quarter codes) heading the page's columns; by their
    dates when each column has one and the years alone do not tell (Kraft Heinz: "December 31, 2016 (52 weeks)
    January 3, 2016 (53 weeks) December 28, 2014")."""
    if dates and len(dates) == len(years) >= 2 and len(nums) >= len(years) and not quarters \
            and (len(set(years)) < len(years) or max(years) - 1 not in years):
        cur_i = dates.index(max(dates))
        prev = [i for i, d in enumerate(dates) if 350 <= (dates[cur_i] - d).days <= 380]
        return nums[cur_i], (nums[prev[0]] if prev else None)
    if quarters and len(nums) >= len(quarters):
        top = max(quarters)
        cur_i = quarters.index(top)
        same = (top[0] - 1, top[1])                       # the same quarter a year earlier
        prev_i = quarters.index(same) if same in quarters else None
        return nums[cur_i], (nums[prev_i] if prev_i is not None else None)
    if len(years) >= 2 and len(nums) >= len(years):
        top = max(years)
        cur_i = years.index(top)
        prev_i = years.index(top - 1) if top - 1 in years else None
        if prev_i is None and len(years) == 2 and top - min(years) == 2:
            prev_i = 1 - cur_i                         # a 53-week year: "January 3, 2016 and December 28, 2014"
        return nums[cur_i], (nums[prev_i] if prev_i is not None else None)
    if len(years) >= 2 and years[0] < years[-1]:          # ascending columns, some cells empty: the last ones
        return nums[-1], (nums[-2] if len(nums) > 1 else None)
    return nums[0], (nums[1] if len(nums) > 1 else None)


def _share_scale(metrics: dict) -> None:
    """Diluted shares printed in thousands or millions under a header that only says so for the amounts: the scale
    that makes net income / diluted EPS equal the share count (within a third)."""
    sh, ni, eps = (metrics.get(k) for k in ("diluted_shares", "net_income", "eps_diluted"))
    if not (sh and ni and eps):
        return
    for w in ("cur", "prev"):
        a, b, c = sh.get(w), ni.get(w), eps.get(w)
        if not (a and b and c) or not a["value"] or not c["value"]:
            continue
        implied = b["value"] / c["value"]
        if implied <= 0:
            continue
        base = a["value"] / (a.get("scale") or 1)
        best = min((1.0, 1e3, 1e6, 1e9), key=lambda k: abs(math.log(base * k / implied)))
        if abs(math.log(base * best / implied)) < 0.3:
            a["value"] = base * best


def extract(facts: list[dict], page_text: dict[int, str]) -> dict:
    """facts: [{id, label, value, display, page}] -> {"metrics", "currency", "years", "periods"} like financials.extract()."""
    # the column header, period and scale of a page are those of the statement on it, wherever it starts
    raw = page_text
    page_text = {p: t[statement_start(t):] for p, t in page_text.items()}
    before_of = {p: (p - 1 if p - 1 in page_text else p - 2 if p - 2 in page_text and p - 1 not in page_text else None) for p in page_text}
    for p in sorted(page_text):
        # a page that carries on the statement before it: read with that statement's title, scale and column years
        # (the last statement of that page: a release prints its balance sheet under its statement of income)
        q = before_of[p]                               # the page before (past a blank page that was not read)
        last = list(_headings(raw[q])) if q else []
        foot = foot_title(raw[q]) if q else None
        if foot:
            last = [foot]                              # the statement titled at the foot of the page before
        if last and not title_match(page_text[p]) \
                and not re.search(r"notes to|report of independent|discussion and analysis|statements? of|balance sheets?|quarterly|selected financial",
                                  _head(page_text[p]), re.I) and not re.search(r"statements? of|balance sheets?", page_text[p][-300:], re.I):
            prev = raw[q][last[-1].start():]
            row = re.search(r"\(?\$?\s?\d{1,3}(,\d{3})+", prev)           # the header ends where the first amount is
            page_text[p] = prev[:min(row.start() if row else 300, 400)] + " " + page_text[p]
    from datetime import date
    import calendar
    from . import financials as F
    from .tables import period_label
    from .i18n import lang
    groups: dict[tuple[int, str], list[dict]] = {}
    for f in facts:
        groups.setdefault((f["page"], f["label"]), []).append(f)
    note_col = {p: note_column(t) for p, t in page_text.items()}
    cols = {p: page_columns([f for f in facts if f["page"] == p], note_col[p]) for p in page_text}
    found: dict[str, list] = {}
    for (page, label), fs in groups.items():
        key = match(label)
        nums = sorted((f for f in fs if not f.get("inline")), key=lambda f: f["id"])   # not "net of $35, $46 and $32" in a label
        ys = header_years(page_text.get(page, ""))
        if key == "net_income" or re.match(r"(net )?(income|earnings|loss|\(loss\) income|income \(loss\)|\(loss\) earnings|earnings \(loss\))"
                                            r"( \(loss\))? per (common |ordinary )?share\b", _clean(label)):
            # the result per share under "Basic …" and then "Diluted earnings per share" headings, on the same label
            ps = [f for f in nums if is_per_share(f)]
            # the columns: as many as the years over them ("2023 2022 | 2023 2022": a quarter and the year to date), or
            # as many as the distinct years when the header names them twice ("2016, 2015, AND 2014  2016 2015 2014")
            n = next((k for k in (len(ys), len(dict.fromkeys(ys))) if k >= 2 and len(ps) == 2 * k), 0) if len(ys) >= 2 else 0
            if n and len(ps) == 2 * n and re.search(r"basic.{0,600}?diluted", page_text.get(page, ""), re.I | re.S):
                found.setdefault("eps_diluted", []).append((page, ps[n:], _clean(label) + " diluted (heading)", None))
            if key == "net_income" and ps and len(ps) == len(nums):
                continue                                   # only per-share figures: not the amount
        if not key:
            continue
        nums = _amounts(_drop_note_ref(nums, ys, note_col.get(page, False)), key)
        if key == "eps_diluted" and _clean(label) == "diluted" and not any(re.search(r"\d[.,]\d\d$", f["display"].strip("()$ ")) for f in nums):
            continue                                       # a bare "Diluted" row of share counts, not earnings per share
        if not nums:
            continue
        n = len(header_quarters(page_text.get(page, ""))) or len(dict.fromkeys(ys))
        row = _drop_note_ref(sorted((f for f in fs if not f.get("inline")), key=lambda f: f["id"]), ys, note_col.get(page, False))
        cells = by_position(row if key not in PER_SHARE else nums, cols.get(page, []), n)
        if cells is not None and key not in PER_SHARE:
            kept = {id(f) for f in _amounts(row, key)}   # the amounts of the row, not its per-share figures or percentages
            cells = [f if f is not None and id(f) in kept else None for f in cells]
        found.setdefault(key, []).append((page, nums, _clean(label), cells))
    # statements are the pages titled as such, then the pages where most metrics were recognised
    page_hits: dict[int, int] = {}
    for key, cands in found.items():
        for page, *_ in cands:
            page_hits[page] = page_hits.get(page, 0) + 1
    def title_score(t: str, whole: str = "") -> int:
        m = title_match(t) or next(_titles(t, len(t)), None)   # or one further down (Arctic Paper's cash flow statement under
        if not m:                                              # the end of its balance sheet)
            return 0
        head = t[:700].lower() + " " + t[max(0, m.start() - 60):m.end()].lower()    # "Consolidated" before a title lower down
        if re.search(NOT_PRIMARY, t[:700] + " " + m.group(), re.I):     # as printed: "Elkem ASA" is a legal entity
            return 1
        if len(re.findall(r"\d{1,3}(?:,\d{3}){2,}\.\d\d\b", t)) >= 5:
            return 1                       # amounts to the cent ("32,298,207.32"): a company's statutory accounts, not the group's
        # "Group income statement", "Statement of financial position of the Group": the group's, as "consolidated"
        i = whole.find(m.group())                  # the page before the cut: "Consolidated " right before "cash flow statement"
        before = whole[max(0, i - 60):i].lower() if i > 0 else ""
        return 3 if "consolidat" in head or "consolidat" in before or re.search(r"\bgroup\b", t[max(0, m.start() - 40):m.end() + 40], re.I) else 2
    titled = {p: title_score(t, raw[p]) for p, t in page_text.items()}
    kind_of = {p: page_statement(t) for p, t in page_text.items()}
    kinds = {p: page_kinds(raw[p]) | {kind_of[p]} for p in page_text}
    for p in sorted(page_text):
        first = next(_titles(raw[p], len(raw[p])), None)
        top = raw[p][:first.start()] if first else raw[p]
        q = before_of[p]
        before = [m for m in _headings(raw[q])] if q else []
        foot = foot_title(raw[q]) if q else None
        if foot:
            before = [foot]
        if before and len(re.findall(r"\d,\d{3}", top)) >= 2:
            # its top carries on the last statement of the page before (a release's cash flow statement under its
            # statement of income goes on overleaf)
            kinds[p].add(page_statement(before[-1].group()) or kind_of[q])
    kinds = {p: k - {""} for p, k in kinds.items()}
    # the document's own statements: those of its latest year (not an investee's older ones printed after them), in
    # full rather than condensed (a 10-K's quarterly restatements)
    year_of = {p: max(header_years(t) or [0]) for p, t in page_text.items()}
    top_year = max((year_of[p] for p in page_text if titled[p] >= 2 and kinds[p]), default=0)

    def condensed(t: str) -> bool:
        m = title_match(t)
        return bool(m and re.search(r"condensed", t[max(0, m.start() - 60):m.end() + 40], re.I))   # "Balance sheet condensed by main items"
    cond = {p: condensed(t) for p, t in page_text.items()}
    # a statement page that states no scale (3M prints "(Millions…)" on all but one): the one the others state
    scales = [page_scale(t) for p, t in page_text.items() if titled[p] >= 2 and kinds[p] and page_scale(t) != 1.0]
    doc_scale = max(set(scales), key=scales.count) if scales and len(set(scales)) == 1 else 1.0

    def kind_rows(pg: int, kind: str) -> int:
        """How many lines of that statement the page has: the statement itself over a summary of it (Arctic Paper)."""
        return len({k for k, cs in found.items() if statement_of(k) == kind and any(c[0] == pg for c in cs)})

    metrics, years = {}, None
    head: dict[str, dict] = {}
    equity_page = {p for p, t in page_text.items() if EQ_TITLE.search(t[:700])}
    for key, cands in found.items():
        has_statement = any(statement_of(key) in ks and titled.get(p, 0) >= 2 for p, ks in kinds.items())
        if has_statement:
            # with the consolidated statement at hand, its lines from it only: not a figure elsewhere (a segment's, a
            # quarter's, the MD&A's), the parent company's or the guarantors' statements, the statement of equity
            cands = [c for c in cands if statement_of(key) in kinds[c[0]] and titled.get(c[0], 0) >= 2]
            # with the group's consolidated statement at hand, not one titled without "consolidated": the parent
            # company's own statements, which European reports print after the group's ("Statement of Financial Position")
            if any(statement_of(key) in kinds[p] and titled[p] == 3 for p in page_text):
                cands = [c for c in cands if titled[c[0]] == 3]
            if any(year_of[p] >= top_year and statement_of(key) in kinds[p] and titled[p] >= 2 for p in page_text):
                cands = [c for c in cands if not 0 < year_of[c[0]] < top_year]  # not an investee's older statements
                if not cands:
                    continue
            if not cands:
                continue
        else:
            # no statement titled as such: not from the parent company's statements either (AKVA, whose group
            # statements did not print as text): a line not read rather than the parent's figure as the group's
            cands = [c for c in cands if not re.search(NOT_PRIMARY, raw[c[0]][:900], re.I)]
            if any(titled[p] >= 2 for p in page_text):
                # other statements found, not this one: a page that looks like it, not any table with the line (Elkem's
                # net income from a table of its equity-accounted investments)
                kind = statement_of(key)
                rows = {pg: len({k for k, cs in found.items() if statement_of(k) == kind and any(c[0] == pg for c in cs)}) for pg in page_text}
                equity = {pg for pg in page_text if len(re.findall(r"share premium|treasury shares|retained earnings|other reserves", raw[pg][:600], re.I)) >= 2}
                cands = [c for c in cands if kind in kinds[c[0]] or (rows[c[0]] >= 3 and c[0] not in equity)]   # Costco: a balance sheet with no title
            if not cands:
                continue
        page, nums, label, cells = max(cands, key=lambda c: (titled.get(c[0], 0) >= 2 and statement_of(key) in kinds[c[0]],
                                                   year_of[c[0]] >= top_year, not cond[c[0]], titled.get(c[0], 0),
                                                   kind_rows(c[0], statement_of(key)), page_hits[c[0]], kind_of.get(c[0]) == statement_of(key),
                                                   _line_rank(key, c[2]),
                                                   len(c[1]) >= 2, -c[0],
                                                   # the balance sheet's own total over a smaller table's on its page (VIEs)
                                                   abs(c[1][0]["value"]) if key in ("total_assets", "total_liabilities", "liab_and_equity") else 0))
        text = page_text.get(page, "")
        ys = header_years(text)
        qs = header_quarters(text)
        if cells is not None and any(cells):
            nums = cells                               # by where each figure sits under the column headers
        elif ys and not qs and len(nums) < len(ys):
            nums = _with_dashes(nums, label, text, len(ys))
        cur_f, prev_f = _columns(nums, ys, qs, header_dates(text, ys) if ys else None)
        if cur_f is None:
            continue                                   # nothing in the current column ("—")
        scale = 1.0 if key in PER_SHARE else (page_scale(text) if page_scale(text) != 1.0 else doc_scale)
        kind = F.METRICS[key][2] if key in F.METRICS else "flow"
        if kind == "shares":
            m = re.search(r"\bshares?\b[^.;)]{0,60}?\bin (thousands|millions)", text[:2500], re.I)
            if m:
                scale = 1e3 if m.group(1).lower() == "thousands" else 1e6
            elif not re.search(r"(thousands|millions),? except (per[- ](common )?share|share)", text[:2500], re.I):
                scale = 1.0                            # counts in units unless the header scales them too

        def fd(f):
            v = abs(f["value"]) if key in ("capex", "buybacks", "dividends", "cost_of_revenue", "rnd", "interest_expense") else f["value"]
            if key == "income_tax":
                v = tax_expense(label, f["value"])
            return {"id": f["id"], "value": v * scale, "display": f["display"], "page": f["page"], "concept": "", "unit": "", "scale": scale}

        metrics[key] = {"key": key, "kind": "ps" if key in PER_SHARE else kind, "cur": fd(cur_f),
                        "prev": fd(prev_f) if prev_f and prev_f is not cur_f else None}
        side = "stock" if kind == "stock" else "flow"
        if (ys or qs) and side not in head:
            head[side] = {**page_period(text), "years": ys or [y for y, _ in qs], "quarters": qs, "dates": header_dates(text, ys) if ys else []}
        if ys and years is None:
            years = (max(ys), max(ys) - 1)
    _share_scale(metrics)
    periods = {}
    for side, h in head.items():
        if h["quarters"]:
            (y, q) = max(h["quarters"])
            periods[side] = [f"{q}Q{str(y)[2:]}", f"{q}Q{str(y - 1)[2:]}" if (y - 1, q) in h["quarters"] else ""]
            continue
        top = max(h["years"])

        def end(y):
            # the date printed over the column when there is one, else the period's month and day
            for d in h["dates"]:
                if d.year == y:
                    return d
            return date(y, h["month"], min(h["day"], calendar.monthrange(y, h["month"])[1]))
        if side == "stock":
            periods[side] = [period_label(None, end(top), lang()), period_label(None, end(top - 1), lang()) if top - 1 in h["years"] else ""]
        elif h.get("fiscal_q") and (h["months"] or 3) == 3:
            # "Second Quarter 2023 / 2022" without dates: the company's own quarter
            q = h["fiscal_q"]
            from .i18n import t
            periods[side] = [t("{q}° trim. {y}", "Q{q} {y}", q=q, y=top), t("{q}° trim. {y}", "Q{q} {y}", q=q, y=top - 1)]
        else:
            months = h["months"] or 12
            periods[side] = [period_label(months, end(top), lang()), period_label(months, end(top - 1), lang())]
    cur = next((page_currency(page_text.get(m["cur"]["page"], "")) for m in metrics.values()), "")
    return {"metrics": metrics, "currency": cur, "years": years, "periods": periods or None}
